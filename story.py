import time
import sys

# ── 打字機輸出 ────────────────────────────────────────────
def typewrite(text, delay=0.03, newline=True):
    for ch in text:
        sys.stdout.write(ch)
        sys.stdout.flush()
        time.sleep(delay)
    if newline:
        print()


def narrate(lines, delay=0.03, pause=0.6):
    """輸出一段敘事文字，每行有打字機效果"""
    print()
    for line in lines:
        if line == "":
            print()
            time.sleep(pause * 0.5)
        else:
            typewrite("  " + line, delay=delay)
            time.sleep(pause * 0.3)
    time.sleep(pause)


def scene_break():
    print("\n  " + "─" * 44)
    time.sleep(0.4)


def press_enter():
    input("\n  【按 Enter 繼續…】")


