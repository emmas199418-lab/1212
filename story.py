def talk_to_npc(area_name):
    npcs = NPCS.get(area_name, [])
    if not npcs:
        print("\n  這裡沒有可以交談的人。")
        return
    print(f"\n  ══ 交談 ══")
    for i, npc in enumerate(npcs, 1):
        print(f"   {i}. {npc['name']}")
    print("   0. 取消")

    choice = input("  選擇要交談的對象：").strip()
    if choice == "0" or not choice.isdigit():
        return
    idx = int(choice) - 1
    if not (0 <= idx < len(npcs)):
        print("  無效選項。")
        return

    npc = npcs[idx]
    print()
    for line in npc["dialogues"]:
        typewrite("  " + line, delay=0.03)
        time.sleep(0.4)
    press_enter()
